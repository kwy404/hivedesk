// Builds hivedesk-setup.exe (online: downloads the app package, a few hundred KB) and, with --offline,
// hivedesk-setup-offline.exe (the package inside). Windows only: uses the C# compiler that ships with Windows
// (.NET Framework 4.8) and WPF, nothing to install. Used by .github/workflows/desktop.yml.
//   node desktop/scripts/build-setup.mjs --zip dist/hivedesk-windows-x64.zip --out dist/hivedesk-setup.exe
//     [--offline dist/hivedesk-setup-offline.exe] [--version 1.0.0] [--url <package url>]
// The online installer pins the package by its SHA-256 and size, so it installs exactly that file.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..', '..');
const SRC = path.join(ROOT, 'desktop', 'installer', 'windows');
const opts = {};
for (let i = 2; i < process.argv.length; i += 2) opts[process.argv[i].replace(/^--/, '')] = process.argv[i + 1];
if (!opts.zip || !opts.out) {
  console.error('usage: build-setup.mjs --zip <hivedesk-windows-x64.zip> --out <hivedesk-setup.exe> [--offline <offline exe>] [--version x.y.z] [--url <url>]');
  process.exit(2);
}
const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));
const version = opts.version || pkg.version;
const url = opts.url || `https://github.com/kwy404/hivedesk/releases/download/v${version}/hivedesk-windows-x64.zip`;
const zip = fs.readFileSync(opts.zip);
const sha256 = crypto.createHash('sha256').update(zip).digest('hex');

/** The sum of the uncompressed sizes in the zip's central directory: the space the install needs. */
function unpackedSize(buf) {
  let eocd = -1;
  for (let i = buf.length - 22; i >= Math.max(0, buf.length - 65557); i--) if (buf.readUInt32LE(i) === 0x06054b50) { eocd = i; break; }
  if (eocd < 0) throw new Error('not a zip file');
  let p = buf.readUInt32LE(eocd + 16);
  let total = 0;
  for (let n = buf.readUInt16LE(eocd + 10); n > 0; n--) {
    total += buf.readUInt32LE(p + 24);
    p += 46 + buf.readUInt16LE(p + 28) + buf.readUInt16LE(p + 30) + buf.readUInt16LE(p + 32);
  }
  return total;
}

const fw = path.join(process.env.WINDIR || 'C:\\Windows', 'Microsoft.NET', 'Framework64', 'v4.0.30319');
const csc = path.join(fw, 'csc.exe');
if (!fs.existsSync(csc)) throw new Error(`no C# compiler at ${csc}`);
const work = fs.mkdtempSync(path.join(os.tmpdir(), 'hivedesk-setup-build-'));
const numeric = version.replace(/[-+].*$/, '').split('.').concat(['0']).slice(0, 4).join('.');
const cs = (s) => JSON.stringify(s);
fs.writeFileSync(path.join(work, 'Payload.cs'), [
  '// Generated by desktop/scripts/build-setup.mjs: the app package this installer installs.',
  'namespace HivedeskSetup',
  '{',
  '    public static class Payload',
  '    {',
  `        public const string Version = ${cs(version)};`,
  `        public const string AssemblyVersion = ${cs(numeric)};`,
  `        public const string Url = ${cs(url)};`,
  `        public const string Sha256 = ${cs(sha256)};`,
  `        public const long Size = ${zip.length};`,
  `        public const long InstalledSize = ${unpackedSize(zip)};`,
  '    }',
  '}',
  ''
].join('\n'));

function build(out, extraResources) {
  fs.mkdirSync(path.dirname(path.resolve(out)), { recursive: true });
  const res = (file, name) => `-resource:${file},${name}`;
  const args = [
    '-nologo', '-target:winexe', '-optimize+', '-platform:anycpu', `-out:${path.resolve(out)}`,
    `-win32icon:${path.join(ROOT, 'desktop', 'icons', 'hivedesk.ico')}`, `-win32manifest:${path.join(SRC, 'app.manifest')}`,
    ...['PresentationFramework.dll', 'PresentationCore.dll', 'WindowsBase.dll'].map((d) => `-r:${path.join(fw, 'WPF', d)}`),
    ...['System.Xaml.dll', 'System.Web.Extensions.dll', 'System.IO.Compression.dll', 'System.IO.Compression.FileSystem.dll', 'System.Windows.Forms.dll'].map((d) => `-r:${path.join(fw, d)}`),
    res(path.join(SRC, 'strings.json'), 'strings.json'), res(path.join(SRC, 'Theme.xaml'), 'Theme.xaml'), res(path.join(SRC, 'Art.xaml'), 'Art.xaml'),
    res(path.join(ROOT, 'LICENSE'), 'LICENSE'), res(path.join(ROOT, 'desktop', 'profile', 'avatars.json'), 'avatars.json'), res(path.join(ROOT, 'desktop', 'icons', 'hivedesk.ico'), 'hivedesk.ico'),
    ...extraResources,
    path.join(SRC, 'Core.cs'), path.join(SRC, 'Ui.cs'), path.join(SRC, 'Setup.cs'), path.join(work, 'Payload.cs')
  ];
  execFileSync(csc, args, { stdio: 'inherit' });
  const size = fs.statSync(out).size;
  console.log(`build-setup: ${out} (${(size / 1e6).toFixed(2)} MB) installs hivedesk ${version}, package ${sha256.slice(0, 12)}...`);
}

build(opts.out, []);
if (opts.offline) build(opts.offline, [`-resource:${path.resolve(opts.zip)},payload.zip`, `-resource:${path.resolve(opts.out)},uninstall.exe`]);
fs.rmSync(work, { recursive: true, force: true });
